"""Ecosystem-aware file templates for adoption scaffolding.

Provides templates for reproducibility.yml, data/README.md,
results/README.md, GitHub Actions workflow, and other scaffolding files.
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass
class ScaffoldTemplate:
    """A template for a scaffoldable file."""
    id: str
    title: str
    path: str
    description: str
    risk: str = "low"  # low, medium, high
    requires_confirmation: bool = False
    content: str = ""


def generate_reproducibility_yml(
    ecosystems: list[dict] | None = None,
    project_name: str = "my-paper",
    project_type: str = "analysis",
) -> str:
    """Generate a reproducibility.yml template based on detected ecosystems."""
    eco = ecosystems[0] if ecosystems else {}
    eco_id = eco.get("id", "python")
    env_type = eco_id if eco_id in ("python", "r", "julia", "other") else "other"

    # Build install commands from ecosystem
    install_cmds = eco.get("install_plan", [])
    run_cmds = eco.get("run_plan", [])
    install_cmd = install_cmds[0] if install_cmds else "echo 'Add your install command'"
    run_cmd = run_cmds[0] if run_cmds else "echo 'Add your run command'"

    # Detect environment file
    env_files = eco.get("environment_files", [])
    env_file = env_files[0] if env_files else "requirements.txt"

    lines = [
        "# OSS-Paper-CI Reproducibility Contract",
        f"# Generated by oss-paper-ci scaffold",
        "",
        f'version: "0.3"',
        f"project_name: {project_name}",
        f"project_type: {project_type}",
        "",
        "paper:",
        '  path: "paper.pdf"',
        "  bibliography: []",
        "",
        "environment:",
        f"  type: {env_type}",
        f'  file: "{env_file}"',
        "",
        "data:",
        "  - id: main-data",
        '    path: "data/"',
        '    availability: "public"',
        '    source: ""',
        "",
        "experiments:",
        "  - id: main-experiment",
        '    description: "Main experiment"',
        f'    command: "{run_cmd}"',
        "    timeout_seconds: 3600",
        "    safe_to_run: true",
        "    expected_outputs:",
        '      - "results/"',
        "",
        "figures: []",
        "",
        "results:",
        "  - id: main-results",
        '    path: "results/"',
        '    generated_by: "main-experiment"',
        "",
        "ci:",
        "  smoke_experiment: main-experiment",
        "  min_score: 60",
        "  fail_on_regression: false",
    ]
    return "\n".join(lines) + "\n"


